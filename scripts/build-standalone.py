#!/usr/bin/env python3
"""Regenerate install-wink.sh from the KWin package sources."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def heredoc(relpath: str, content: str) -> str:
    delim = f"EOF_{relpath.replace('/', '_')}_WINK"
    if delim in content:
        raise SystemExit(f"Delimiter collision for {relpath}")
    if not content.endswith("\n"):
        content += "\n"
    return f"cat > \"${{PKG}}/{relpath}\" << '{delim}'\n{content}{delim}\n"


def main() -> None:
    main_js = (ROOT / "wink/contents/code/main.js").read_text()
    metadata = (ROOT / "wink/metadata.json").read_text()
    config_xml = (ROOT / "wink/contents/config/main.xml").read_text()
    config_ui = (ROOT / "wink/contents/ui/config.ui").read_text()
    apply = (ROOT / "scripts/apply-plasma-config.sh").read_text()
    apply_body = "\n".join(
        line
        for line in apply.splitlines()
        if not line.startswith("#!") and line != "set -euo pipefail"
    )

    parts = [
        "#!/usr/bin/env bash",
        "# Standalone installer: WinK for KDE Plasma 6.",
        "# No repo checkout required. Run: bash install-wink.sh",
        "# Regenerated by: make standalone",
        "set -euo pipefail",
        "",
        'if ! command -v kpackagetool6 >/dev/null 2>&1; then',
        '  echo "error: kpackagetool6 not found (need Plasma 6 / kwin)" >&2',
        "  exit 1",
        "fi",
        'if ! command -v kwriteconfig6 >/dev/null 2>&1; then',
        '  echo "error: kwriteconfig6 not found" >&2',
        "  exit 1",
        "fi",
        "",
        'WORKDIR="$(mktemp -d)"',
        'trap \'rm -rf "$WORKDIR"\' EXIT',
        'PKG="$WORKDIR/wink"',
        'mkdir -p "$PKG/contents/code" "$PKG/contents/config" "$PKG/contents/ui"',
        "",
        heredoc("metadata.json", metadata),
        heredoc("contents/code/main.js", main_js),
        heredoc("contents/config/main.xml", config_xml),
        heredoc("contents/ui/config.ui", config_ui),
        "",
        'SCRIPT_ID="wink"',
        'if kpackagetool6 --type=KWin/Script --list 2>/dev/null | grep -q "$SCRIPT_ID"; then',
        '  echo "Updating existing WinK…"',
        '  kpackagetool6 --type=KWin/Script --upgrade "$PKG"',
        "else",
        '  echo "Installing WinK…"',
        '  kpackagetool6 --type=KWin/Script --install "$PKG"',
        "fi",
        "",
        "# --- apply Plasma config ---",
        apply_body,
        "",
        "echo",
        'echo "Done. Try Meta+Up, then Meta+Up again; Meta+Right then Meta+Up."',
        "",
    ]

    out = ROOT / "install-wink.sh"
    out.write_text("\n".join(parts))
    out.chmod(0o755)
    print(f"Wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
